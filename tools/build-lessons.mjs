// Bundles lessons/*.md into lessons-data.js for the offline lesson viewer.
// Run from anywhere: node tools/build-lessons.mjs
// Output is deterministic — rerunning without lesson changes yields no diff.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lessonsDir = join(root, "lessons");

// Reference (ng16) exercise files per lesson — shown as links in the
// viewer sidebar and validated to exist on every build.
const LESSON_CODE = {
  "01-components-templates": [
    "ng16/src/app/exercises/components/task-badge.component.ts",
    "ng16/src/app/exercises/components/task-panel.component.ts"
  ],
  "02-directives-pipes": [
    "ng16/src/app/exercises/pipes/task-status.pipe.ts",
    "ng16/src/app/exercises/components/task-list.component.ts"
  ],
  "03-services-di": ["ng16/src/app/exercises/services/task-store.service.ts"],
  "04-rxjs-async": ["ng16/src/app/exercises/services/task-feed.service.ts"],
  "05-forms": ["ng16/src/app/exercises/components/task-form.component.ts"],
  "06-routing": [
    "ng16/src/app/exercises/routing/session.service.ts",
    "ng16/src/app/exercises/routing/can-activate-tasks.guard.ts",
    "ng16/src/app/exercises/routing/task.routes.ts",
    "ng16/src/app/exercises/routing/login.component.ts"
  ],
  "07-signals-cd": ["ng16/src/app/exercises/signals/task-stats.service.ts"]
};

const files = readdirSync(lessonsDir)
  .filter((f) => /^\d{2}-[a-z-]+\.md$/.test(f))
  .sort();

if (files.length !== 7) {
  console.error(`expected 7 lessons, found ${files.length} in ${lessonsDir}`);
  process.exit(1);
}

const data = {};
for (const file of files) {
  const slug = file.replace(/\.md$/, "");
  // Strip a BOM and CRLF so the bundle is identical whatever the checkout's
  // line endings (core.autocrlf on Windows) or the editor that saved it.
  const md = readFileSync(join(lessonsDir, file), "utf8")
    .replace(/^﻿/, "")
    .replace(/\r\n?/g, "\n");
  if (!md.startsWith("# ")) {
    console.error(`${file} does not start with an "# " heading`);
    process.exit(1);
  }
  const code = LESSON_CODE[slug];
  if (!code || code.length === 0) {
    console.error(`${slug}: no entries in LESSON_CODE`);
    process.exit(1);
  }
  for (const p of code) {
    if (!existsSync(join(root, p))) {
      console.error(`${slug}: missing code file ${p}`);
      process.exit(1);
    }
  }
  data[slug] = md;
}

const out =
  "// Generated by tools/build-lessons.mjs — do not edit by hand.\n" +
  "window.LESSONS_DATA = " + JSON.stringify(data) + ";\n" +
  "window.LESSON_CODE = " + JSON.stringify(LESSON_CODE, null, 2) + ";\n";

writeFileSync(join(root, "lessons-data.js"), out, "utf8");
console.log(`bundled ${files.length} lessons with ${Object.values(LESSON_CODE).flat().length} code links`);
